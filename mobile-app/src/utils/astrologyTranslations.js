export const translatePlanet = (planetName, language = 'English') => {
    if (!planetName) return '';
    const langObj = ASTRO_TRANSLATIONS[language] || ASTRO_TRANSLATIONS['English'];
    return langObj.planets[planetName] || planetName.substring(0, 2);
};

export const translatePlanetFull = (planetName, language = 'English') => {
    if (!planetName) return '';
    const langObj = ASTRO_TRANSLATIONS[language] || ASTRO_TRANSLATIONS['English'];
    return (langObj.planetsFull && langObj.planetsFull[planetName]) || planetName;
};

export const translateSign = (signName, language = 'English') => {
    if (!signName) return '';
    const langObj = ASTRO_TRANSLATIONS[language] || ASTRO_TRANSLATIONS['English'];
    return langObj.signs[signName] || signName;
};

export const translateNakshatra = (nakshatraName, language = 'English') => {
    if (!nakshatraName) return '';
    const langObj = ASTRO_TRANSLATIONS[language] || ASTRO_TRANSLATIONS['English'];
    if (langObj.nakshatras && langObj.nakshatras[nakshatraName]) {
        return langObj.nakshatras[nakshatraName];
    }
    return nakshatraName;
};
